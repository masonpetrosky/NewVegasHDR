float State::peakNits() const {
  if (config.peakNits > 0)
    return config.peakNits;
  if (display.found && display.maxNits >= 100)
    return display.maxNits;
  return 1000;
}

// ToneMapper picks the look of HDR output. SDR output and SdrExact keep the curve of the shader the game loaded, so
// that they look as the game does without the plugin.
bool State::vanillaPlusCurve(const HdrBlendShader& shader) const {
  if (!shader.replaced || !scrgb || config.sdrExact || config.toneMapper == ToneMapper::Auto)
    return shader.vanillaPlus;
  return config.toneMapper == ToneMapper::VanillaPlus;
}

const HdrBlendShader* State::findHdrBlend(const IDirect3DPixelShader9* shader) {
  if (!shader)
    return nullptr;
  const int n = hdrBlendCount.load(std::memory_order_acquire);
  for (int i = 0; i < n; ++i)
    if (hdrBlends[i].shader == shader)
      return &hdrBlends[i];
  return nullptr;
}

const char* formatName(D3DFORMAT format) {
  switch (format) {
    case D3DFMT_UNKNOWN: return "UNKNOWN";
    case D3DFMT_A8R8G8B8: return "A8R8G8B8";
    case D3DFMT_X8R8G8B8: return "X8R8G8B8";
    case D3DFMT_R5G6B5: return "R5G6B5";
    case D3DFMT_A1R5G5B5: return "A1R5G5B5";
    case D3DFMT_A4R4G4B4: return "A4R4G4B4";
    case D3DFMT_A8: return "A8";
    case D3DFMT_A2B10G10R10: return "A2B10G10R10";
    case D3DFMT_A8B8G8R8: return "A8B8G8R8";
    case D3DFMT_G16R16: return "G16R16";
    case D3DFMT_A2R10G10B10: return "A2R10G10B10";
    case D3DFMT_A16B16G16R16: return "A16B16G16R16";
    case D3DFMT_L8: return "L8";
    case D3DFMT_A8L8: return "A8L8";
    case D3DFMT_L16: return "L16";
    case D3DFMT_V8U8: return "V8U8";
    case D3DFMT_Q8W8V8U8: return "Q8W8V8U8";
    case D3DFMT_D16: return "D16";
    case D3DFMT_D24S8: return "D24S8";
    case D3DFMT_D24X8: return "D24X8";
    case D3DFMT_D32: return "D32";
    case D3DFMT_D24FS8: return "D24FS8";
    case D3DFMT_R16F: return "R16F";
    case D3DFMT_G16R16F: return "G16R16F";
    case D3DFMT_A16B16G16R16F: return "A16B16G16R16F";
    case D3DFMT_R32F: return "R32F";
    case D3DFMT_G32R32F: return "G32R32F";
    case D3DFMT_A32B32G32R32F: return "A32B32G32R32F";
    case D3DFMT_DXT1: return "DXT1";
    case D3DFMT_DXT3: return "DXT3";
    case D3DFMT_DXT5: return "DXT5";
    default: break;
  }
  static thread_local char buf[16];
  const DWORD f = static_cast<DWORD>(format);
  if (f > 0xFFFF) {  // FourCC formats: INTZ, NULL, ATI2, DF24, RESZ, ...
    buf[0] = static_cast<char>(f), buf[1] = static_cast<char>(f >> 8), buf[2] = static_cast<char>(f >> 16),
    buf[3] = static_cast<char>(f >> 24), buf[4] = 0;
  } else {
    std::snprintf(buf, sizeof buf, "format %lu", f);
  }
  return buf;
}

extern "C" __declspec(dllexport) bool NVSEPlugin_Query(const nvse::Interface* nvse, nvse::PluginInfo* info) {
  info->infoVersion = nvse::PluginInfo::kInfoVersion;
  info->name = "NewVegasHDR";
  info->version = 1;
  return !nvse->isEditor;
}

extern "C" __declspec(dllexport) bool NVSEPlugin_Load(const nvse::Interface* nvse) {
  if (nvse->isEditor)
    return false;
  init();
  return true;
}
