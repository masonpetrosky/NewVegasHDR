constexpr char kVersion[] = "0.1.0";
constexpr float kScrgbWhiteNits = 80;  // scRGB 1.0

template <typename T>
const DWORD* bytecode(const T& array) {
  return reinterpret_cast<const DWORD*>(array);
}

// The file name of the module that holds some code, for the log: who else hooks what.
std::wstring moduleOf(const void* address) {
  HMODULE module = nullptr;
  wchar_t path[MAX_PATH] = L"?";
  if (GetModuleHandleExW(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
                         static_cast<LPCWSTR>(address), &module))
    GetModuleFileNameW(module, path, MAX_PATH);
  return std::filesystem::path(path).filename().wstring();
}

void logConfig() {
  const Config& c = g.config;
  LOG("config: HDR %d, peak %.0f nits (%s), paper white %.0f nits, tonemapper %s, highlight range %.2f, shoulder at "
      "%.2f of peak, gamma %.2f; replace shaders %d, upgrade render targets %d, SDR exact %d, force HDR %d",
      c.hdr, g.peakNits(), c.peakNits > 0 ? "from the ini" : "from Windows", c.paperWhiteNits,
      c.toneMapper == ToneMapper::Auto ? "auto" : (c.toneMapper == ToneMapper::Vanilla ? "vanilla" : "Vanilla Plus"),
      c.highlightRange, c.shoulderStart, c.gamma, c.replaceShaders, c.upgradeRenderTargets, c.sdrExact, c.forceHdr);
}

void logPresentParameters(const char* what, const D3DPRESENT_PARAMETERS& pp) {
  LOG("%s: %ux%u %s x%u, msaa %d (quality %lu), swap effect %d, windowed %d, auto depth %d (%s), flags 0x%lx, "
      "refresh %u, interval 0x%x",
      what, pp.BackBufferWidth, pp.BackBufferHeight, formatName(pp.BackBufferFormat), pp.BackBufferCount,
      static_cast<int>(pp.MultiSampleType), pp.MultiSampleQuality, static_cast<int>(pp.SwapEffect), pp.Windowed,
      pp.EnableAutoDepthStencil, formatName(pp.AutoDepthStencilFormat), pp.Flags, pp.FullScreen_RefreshRateInHz,
      pp.PresentationInterval);
}

