// A surface's shape for the recon notes: the back buffer, or its size and format.
std::string shape(IDirect3DSurface9* s) {
  if (!s)
    return "none";
  if (s == g.backBuffer)
    return "back buffer";
  D3DSURFACE_DESC d;
  if (FAILED(masquerade::realDesc(s, &d)))
    return "?";
  char buf[96];
  std::snprintf(buf, sizeof buf, "%ux%u %s%s pool %d", d.Width, d.Height, formatName(d.Format),
                d.MultiSampleType ? " msaa" : "", static_cast<int>(d.Pool));
  return buf;
}

// Logs the first draw of each distinct HDR blend setup: which target it writes and what it reads.
void noteHdrBlendDraw(IDirect3DDevice9* device, const HdrBlendShader& shader) {
  static std::vector<std::string> seen;
  if (seen.size() >= 16)
    return;
  IDirect3DSurface9* target = nullptr;
  device->GetRenderTarget(0, &target);
  std::string key = std::string(hdrBlendName(shader.kind)) + " -> " + shape(target);
  if (target)
    target->Release();
  for (const auto& s : seen)
    if (s == key)
      return;
  seen.push_back(key);
  LOG("HDR blend draw: %s (%s, %s) writes %s; bloom %s; scene %s", hdrBlendName(shader.kind),
      shader.replaced ? "ours" : "the game's", g.vanillaPlusCurve(shader) ? "Vanilla Plus curve" : "vanilla curve",
      trace::describeTarget(device).c_str(), trace::describeStage(device, 0).c_str(),
      trace::describeStage(device, 1).c_str());
}

// Logs the first copy of each kind between two kinds of surface (save game thumbnails, menu backgrounds, resolves).
void noteCopy(const char* call, IDirect3DSurface9* from, IDirect3DSurface9* to) {
  static std::vector<std::string> seen;
  if (seen.size() >= 48)
    return;
  std::string key = std::string(call) + ": " + shape(from) + " -> " + shape(to);
  for (const auto& s : seen)
    if (s == key)
      return;
  seen.push_back(key);
  LOG("copy %s", key.c_str());
}

