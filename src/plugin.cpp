bool enableScrgb(IDirect3DDevice9* device) {
  IDirect3DSwapChain9* swapChain = nullptr;
  if (FAILED(device->GetSwapChain(0, &swapChain)))
    return false;
  ID3D9VkExtSwapchain* ext = nullptr;
  swapChain->QueryInterface(__uuidof(ID3D9VkExtSwapchain), reinterpret_cast<void**>(&ext));
  swapChain->Release();
  if (!ext) {
    LOG("HDR: the swap chain has no DXVK extension interface; staying SDR");
    return false;
  }
  bool ok = false;
  if (!ext->CheckColorSpaceSupport(dxvk::kExtendedSrgbLinear)) {
    LOG("HDR: DXVK offers no scRGB colour space for this display; staying SDR");
  } else if (HRESULT hr = ext->SetColorSpace(dxvk::kExtendedSrgbLinear); FAILED(hr)) {
    LOG("HDR: SetColorSpace(scRGB) failed (0x%08lx); staying SDR", hr);
  } else {
    dxvk::HdrMetadata md = {};
    md.redPrimary[0] = 0.640f, md.redPrimary[1] = 0.330f;
    md.greenPrimary[0] = 0.300f, md.greenPrimary[1] = 0.600f;
    md.bluePrimary[0] = 0.150f, md.bluePrimary[1] = 0.060f;
    md.whitePoint[0] = 0.3127f, md.whitePoint[1] = 0.3290f;
    md.maxLuminance = g.peakNits();
    md.minLuminance = 0;
    md.maxContentLightLevel = g.peakNits();
    md.maxFrameAverageLightLevel = g.config.paperWhiteNits;
    ext->SetHDRMetaData(&md);
    LOG("HDR: swap chain switched to scRGB");
    ok = true;
  }
  ext->Release();
  return ok;
}

// The copy of the back buffer is a default pool texture and D3D9 wants state blocks gone too before a Reset.
void releaseResetResources() {
  if (g.frameCopy) {
    g.frameCopy->Release();
    g.frameCopy = nullptr;
  }
  if (g.stateBlock) {
    g.stateBlock->Release();
    g.stateBlock = nullptr;
  }
  masquerade::releaseResources();
}

bool ensureEncodeResources(IDirect3DDevice9* device) {
  InternalScope internal;
  if (!g.encodeVs)
    g.d3d.createVertexShader(device, bytecode(g_encodeVs), &g.encodeVs);
  if (!g.encodePs)
    g.d3d.createPixelShader(device, bytecode(g_encodePs), &g.encodePs);
  if (!g.encodeDecl) {
    const D3DVERTEXELEMENT9 elements[] = {
        {0, 0, D3DDECLTYPE_FLOAT4, D3DDECLMETHOD_DEFAULT, D3DDECLUSAGE_POSITION, 0}, D3DDECL_END()};
    device->CreateVertexDeclaration(elements, &g.encodeDecl);
  }
  if (!g.stateBlock)
    device->CreateStateBlock(D3DSBT_ALL, &g.stateBlock);
  if (!g.frameCopy)
    g.d3d.createTexture(device, g.width, g.height, 1, D3DUSAGE_RENDERTARGET, D3DFMT_A16B16G16R16F, D3DPOOL_DEFAULT,
                        &g.frameCopy, nullptr);
  static bool logged = false;
  const bool ok = g.encodeVs && g.encodePs && g.encodeDecl && g.stateBlock && g.frameCopy;
  if (!ok && !logged) {
    logged = true;
    LOG("HDR: could not create the encode pass (vs %p, ps %p, decl %p, state %p, copy %p)",
        static_cast<void*>(g.encodeVs), static_cast<void*>(g.encodePs), static_cast<void*>(g.encodeDecl),
        static_cast<void*>(g.stateBlock), static_cast<void*>(g.frameCopy));
  }
  return ok;
}

// Draws the copy of the frame into the back buffer through encode.hlsl with the given encode constants (see there).
// All device state the pass touches is put back afterwards.
void drawFrameCopy(IDirect3DDevice9* device, const float (&encode)[4]) {
  IDirect3DSurface9* backBuffer = nullptr;
  if (FAILED(device->GetBackBuffer(0, 0, D3DBACKBUFFER_TYPE_MONO, &backBuffer)))
    return;
  g.stateBlock->Capture();
  IDirect3DSurface9* targets[4] = {};
  for (DWORD i = 0; i < 4; ++i)
    device->GetRenderTarget(i, &targets[i]);
  IDirect3DSurface9* depth = nullptr;
  device->GetDepthStencilSurface(&depth);

  g.d3d.setRenderTarget(device, 0, backBuffer);
  for (DWORD i = 1; i < 4; ++i)
    if (targets[i])
      g.d3d.setRenderTarget(device, i, nullptr);
  g.d3d.setDepthStencilSurface(device, nullptr);
  D3DVIEWPORT9 viewport = {0, 0, g.width, g.height, 0, 1};
  device->SetViewport(&viewport);
  static const std::pair<D3DRENDERSTATETYPE, DWORD> kStates[] = {
      {D3DRS_ZENABLE, FALSE},          {D3DRS_ZWRITEENABLE, FALSE},       {D3DRS_ALPHABLENDENABLE, FALSE},
      {D3DRS_ALPHATESTENABLE, FALSE},  {D3DRS_STENCILENABLE, FALSE},      {D3DRS_CULLMODE, D3DCULL_NONE},
      {D3DRS_FILLMODE, D3DFILL_SOLID}, {D3DRS_COLORWRITEENABLE, 0xF},     {D3DRS_SRGBWRITEENABLE, FALSE},
      {D3DRS_SCISSORTESTENABLE, FALSE}, {D3DRS_FOGENABLE, FALSE},         {D3DRS_CLIPPLANEENABLE, 0},
      {D3DRS_MULTISAMPLEMASK, 0xFFFFFFFF}};
  for (const auto& [state, value] : kStates)
    device->SetRenderState(state, value);
  device->SetTexture(0, g.frameCopy);
  device->SetSamplerState(0, D3DSAMP_MINFILTER, D3DTEXF_POINT);
  device->SetSamplerState(0, D3DSAMP_MAGFILTER, D3DTEXF_POINT);
  device->SetSamplerState(0, D3DSAMP_MIPFILTER, D3DTEXF_NONE);
  device->SetSamplerState(0, D3DSAMP_ADDRESSU, D3DTADDRESS_CLAMP);
  device->SetSamplerState(0, D3DSAMP_ADDRESSV, D3DTADDRESS_CLAMP);
  device->SetSamplerState(0, D3DSAMP_MAXMIPLEVEL, 0);
  device->SetSamplerState(0, D3DSAMP_SRGBTEXTURE, FALSE);
  device->SetVertexDeclaration(g.encodeDecl);
  g.d3d.setVertexShader(device, g.encodeVs);
  g.d3d.setPixelShader(device, g.encodePs);
  const float constants[2][4] = {{encode[0], encode[1], encode[2], encode[3]},
                                 {1.0f / g.width, 1.0f / g.height, 0, 0}};
  g.d3d.setPixelShaderConstantF(device, 0, constants[0], 2);
  static const float kTriangle[3][4] = {{-1, -1, 0, 1}, {-1, 3, 0, 1}, {3, -1, 0, 1}};
  const bool scene = SUCCEEDED(g.d3d.beginScene(device));  // never end a scene of the game's
  g.d3d.drawPrimitiveUP(device, D3DPT_TRIANGLELIST, 1, kTriangle, sizeof kTriangle[0]);
  if (scene)
    g.d3d.endScene(device);

  for (DWORD i = 0; i < 4; ++i) {
    if (targets[i]) {
      g.d3d.setRenderTarget(device, i, targets[i]);
      targets[i]->Release();
    }
  }
  g.d3d.setDepthStencilSurface(device, depth);
  if (depth)
    depth->Release();
  g.stateBlock->Apply();
  backBuffer->Release();
}

// Decodes the finished frame in place: copy the back buffer (resolving it if it is multisampled), then draw the copy
// back in linear light.
bool encodeFrame(IDirect3DDevice9* device) {
  if (!ensureEncodeResources(device))
    return false;
  InternalScope internal;
  IDirect3DSurface9* backBuffer = nullptr;
  if (FAILED(device->GetBackBuffer(0, 0, D3DBACKBUFFER_TYPE_MONO, &backBuffer)))
    return false;
  IDirect3DSurface9* copy = nullptr;
  g.frameCopy->GetSurfaceLevel(0, &copy);
  const HRESULT hr = g.d3d.stretchRect(device, backBuffer, nullptr, copy, nullptr, D3DTEXF_NONE);
  copy->Release();
  backBuffer->Release();
  if (FAILED(hr)) {
    static bool logged = false;
    if (!logged)
      LOG("HDR: copying the back buffer failed (0x%08lx)", hr);
    logged = true;
    return false;
  }
  drawFrameCopy(device, {g.config.paperWhiteNits / kScrgbWhiteNits, g.peakNits() / kScrgbWhiteNits, g.config.gamma, 0});
  return true;
}

// After the present: puts the game's own gamma-space frame back into the back buffer, so that anything the game draws
// over the previous frame lands on the frame it rendered, never on our scRGB one (which would be decoded twice).
void restoreFrame(IDirect3DDevice9* device) {
  InternalScope internal;
  drawFrameCopy(device, {1, 65504, 1, 0});
}

// What the target of an HDR blend draw keeps of the shader's alpha, as hdr_blend.hlsl's Alpha() takes it: 2 for the
// back buffer when the game made it without alpha, 1 for an 8-bit target the plugin made 16-bit float, 0 otherwise.
float targetAlphaMode() {
  IDirect3DSurface9* target = g.renderTarget0;
  if (!target)
    return 0;
  if (target == g.backBuffer)
    return g.gameFormat == D3DFMT_A8R8G8B8 || g.gameFormat == D3DFMT_A2R10G10B10 ? 1.0f : 2.0f;
  return masquerade::shownFormat(target) != D3DFMT_UNKNOWN ? 1.0f : 0.0f;
}

// The tonemap constants of our HDR blend shaders (c24 and c25), set before each of their draws and put back to the
// game's values after it, in case the engine skips setting constants it believes are already there.
void setToneMapConstants(IDirect3DDevice9* device, const HdrBlendShader& shader) {
  const bool vanillaPlus = g.vanillaPlusCurve(shader);
  const bool hdr = g.scrgb && !g.config.sdrExact;
  const float peak = g.peakNits() / g.config.paperWhiteNits;  // in units of paper white
  // Vanilla Plus's curve, stretched from white (1) towards the peak by HighlightRange.
  const float stretch = hdr ? std::max(1.0f, 1 + g.config.highlightRange * (peak - 1)) : 1.0f;
  const float c[2][4] = {{peak, vanillaPlus ? 1.0f : 0.0f, hdr ? 1.0f : 0.0f, g.config.shoulderStart},
                         {g.config.gamma, 1 / g.config.gamma, stretch, targetAlphaMode()}};
  g.d3d.setPixelShaderConstantF(device, 24, c[0], 2);
}

void restoreGameConstants(IDirect3DDevice9* device) {
  g.d3d.setPixelShaderConstantF(device, 24, g.psConstants[24], 2);
}

